export const DICTIONARIES = { en, zh }

/** Translate through the shell's injected `t`, falling back to English. */
export type Translate = (key: LocaleKey, vars?: Record<string, string | number>) => string

function documentLanguage(): string {
  if (typeof document === 'undefined') return ''
  return (document.documentElement.lang || '').toLowerCase()
}

/** BCP 47 locale for dates and relative times, following `<html lang>`. */
export function uiLocale(): 'zh-CN' | 'en-US' {
  return documentLanguage().startsWith('zh') ? 'zh-CN' : 'en-US'
}

export function translator(t?: (key: string) => string): Translate {
  // Without an injected `t` (older shell), follow `<html lang>` so a Chinese
  // client still gets Chinese instead of silently dropping to English.
  const fallback = documentLanguage().startsWith('zh') ? zh : en
  return (key, vars) => {
    const raw = (t?.(key) ?? fallback[key] ?? en[key] ?? key) as string
    if (vars === undefined) return raw
    return raw.replace(/\{(\w+)\}/g, (match, name: string) =>
      vars[name] === undefined ? match : String(vars[name]))
  }
}
